/**
 * Public events and webhook payloads (architecture/api-conventions.md §9, lld/webhooks.md §4).
 * The same `Event` object is delivered to webhook endpoints and returned by `GET /v1/events`.
 *
 * 0.1.0 covers the types webhooks ingests in Stage 1 (payments + agentpay) plus `ping`;
 * later stages add types (the type enum is open).
 */
import { API_VERSION, ApiVersion } from "../common/auth.js";
import { id } from "../common/ids.js";
import { Livemode, UnixTime } from "../common/primitives.js";
import { openEnum, out, z } from "../common/schema.js";
import { AgentPayment } from "../public/agentpay.js";
import { CheckoutSession, PaymentIntent } from "../public/payments.js";

/** Ping object sent by `POST /v1/webhook_endpoints/{id}/test`. */
export const Ping = out({
  object: z.literal("ping").describe("Always `ping`."),
  webhook_endpoint: id("we"),
}).meta({ id: "Ping", description: "Test delivery to a webhook endpoint." });

/** Public type → object schema and the domain subject it comes from (null = generated by webhooks). */
export const WEBHOOK_TYPES = {
  "checkout.session.completed": { object: CheckoutSession, subject: "evt.payments.checkout_session.completed" },
  "checkout.session.expired": { object: CheckoutSession, subject: "evt.payments.checkout_session.expired" },
  "payment_intent.created": { object: PaymentIntent, subject: "evt.payments.payment_intent.created" },
  "payment_intent.processing": { object: PaymentIntent, subject: "evt.payments.payment_intent.processing" },
  "payment_intent.succeeded": { object: PaymentIntent, subject: "evt.payments.payment_intent.succeeded" },
  "payment_intent.payment_failed": { object: PaymentIntent, subject: "evt.payments.payment_intent.payment_failed" },
  "payment_intent.requires_review": { object: PaymentIntent, subject: "evt.payments.payment_intent.requires_review" },
  "payment_intent.overpaid": { object: PaymentIntent, subject: "evt.payments.payment_intent.overpaid" },
  "payment_intent.canceled": { object: PaymentIntent, subject: "evt.payments.payment_intent.canceled" },
  "agent_payment.settled": { object: AgentPayment, subject: "evt.agentpay.agent_payment.settled" },
  "agent_payment.failed": { object: AgentPayment, subject: "evt.agentpay.agent_payment.failed" },
  ping: { object: Ping, subject: null },
} as const satisfies Record<string, { object: z.ZodType; subject: string | null }>;

export type WebhookType = keyof typeof WEBHOOK_TYPES;
export const WEBHOOK_TYPE_NAMES = Object.keys(WEBHOOK_TYPES) as [WebhookType, ...WebhookType[]];
export const WebhookTypeSchema = openEnum(WEBHOOK_TYPE_NAMES, "Event type.");

/** Domain subject → public type (webhooks ingest mapping). */
export const SUBJECT_TO_WEBHOOK_TYPE: Readonly<Record<string, WebhookType>> = Object.fromEntries(
  Object.entries(WEBHOOK_TYPES)
    .filter(([, v]) => v.subject !== null)
    .map(([t, v]) => [v.subject as string, t as WebhookType]),
);

const RequestInfo = out({
  id: id("req").nullable().describe("API request that caused the event, if any."),
  idempotency_key: z.string().nullable().describe("Idempotency-Key of that request, if any."),
}).describe("Request that caused the event.");

function eventVariant<T extends WebhookType>(type: T, object: z.ZodType) {
  return out({
    id: id("evt"),
    object: z.literal("event").describe("Always `event`."),
    type: z.literal(type).describe("Event type."),
    api_version: ApiVersion.describe("API version the payload is rendered in."),
    created: UnixTime,
    livemode: Livemode,
    data: out({
      object,
      previous_attributes: z
        .record(z.string(), z.unknown())
        .optional()
        .describe("Changed fields with their previous values (update events)."),
    }).describe("Event data."),
    request: RequestInfo,
  }).meta({ id: eventVariantId(type), description: `\`${type}\` event.` });
}

/** Component name of one event variant, e.g. `payment_intent.succeeded` → `EventPaymentIntentSucceeded`. */
export function eventVariantId(type: string): string {
  return `Event${type
    .split(/[._]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("")}`;
}

/** Any public event (discriminated by `type`). */
export const Event = z
  .discriminatedUnion(
    "type",
    WEBHOOK_TYPE_NAMES.map((t) => eventVariant(t, WEBHOOK_TYPES[t].object)) as unknown as [
      ReturnType<typeof eventVariant>,
      ...ReturnType<typeof eventVariant>[],
    ],
  )
  .meta({ id: "Event", description: "A public event; also the body of every webhook delivery." });
export type Event = z.infer<typeof Event>;

// stage 2 — rails-fx (CR-15-04): typed `data.object` per event type
/** The `data.object` type of an event type, e.g. `WebhookObjectOf<"payment_intent.succeeded">` = `PaymentIntent`. */
export type WebhookObjectOf<T extends WebhookType> = z.infer<(typeof WEBHOOK_TYPES)[T]["object"]>;

/**
 * `Event` with `data.object` typed per `type` (a discriminated union TypeScript narrows on
 * `event.type`). Same wire shape as `Event`; `Event`'s inferred type keeps `data.object` untyped.
 */
export type TypedEvent = {
  [T in WebhookType]: Omit<Event, "type" | "data"> & {
    type: T;
    data: { object: WebhookObjectOf<T>; previous_attributes?: Record<string, unknown> | undefined };
  };
}[WebhookType];

/** Any object an event can carry (union of the per-type object schemas). */
export const EventDataObject = z
  .union([CheckoutSession, PaymentIntent, AgentPayment, Ping])
  .describe("Object snapshot carried by an event (`data.object`).");
export type EventDataObject = z.infer<typeof EventDataObject>;
// end stage 2 — rails-fx

/** Envelope schema without per-type validation of `data.object` (consumers tolerant of new types). */
export const EventEnvelopeLoose = out({
  id: id("evt"),
  object: z.literal("event").describe("Always `event`."),
  type: z.string().describe("Event type."),
  api_version: z.string().describe("API version."),
  created: UnixTime,
  livemode: Livemode,
  data: out({
    object: z.record(z.string(), z.unknown()).describe("Object snapshot."),
    previous_attributes: z.record(z.string(), z.unknown()).optional().describe("Previous values."),
  }).describe("Event data."),
  request: RequestInfo,
}).meta({ id: "EventEnvelope", description: "Event envelope (type-agnostic)." });

// ---------------------------------------------------------------------------------------------
// Version rendering (lld/webhooks.md §4: transformers live in @nearpay/spec)
// ---------------------------------------------------------------------------------------------

/** Renders a canonical (latest-version) event object into an older API version. */
export type VersionTransformer = (canonical: Event) => Event;

/** One transformer per supported version; `2026-11-01` is the first version and the identity. */
export const VERSION_TRANSFORMERS: Readonly<Record<z.infer<typeof ApiVersion>, VersionTransformer>> = {
  [API_VERSION]: (e) => e,
};

/** Renders an event for an endpoint pinned to `version`. */
export function renderEvent(canonical: Event, version: z.infer<typeof ApiVersion>): Event {
  const t = VERSION_TRANSFORMERS[version];
  if (!t) throw new Error(`unsupported api version ${version}`);
  return { ...t(canonical), api_version: version };
}
